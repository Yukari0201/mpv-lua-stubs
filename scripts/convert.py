# ── Utility functions ──────────────────────────────────────────────────────────

# Functions that are documented as part of other functions (extracted by the
# code-regex split). We'll track seen ones to avoid duplicates.
_seen_funcs: set = set()


def reset_seen_funcs():
    _seen_funcs.clear()


def is_duplicate(func_name, params_str):
    """Check if a function with the same name and params was already output."""
    key = f"{func_name}({params_str})"
    if key in _seen_funcs:
        return True
    _seen_funcs.add(key)
    return False


def ensure_dir(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)


def read_lines(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.readlines()
    except FileNotFoundError:
        print(f"❌ Error: {path} not found. Run pandoc first.", file=sys.stderr)
        sys.exit(1)


def is_skip_section(line):
    """Check if a heading line should be skipped (e.g. Example, Script location)."""
    for pat in SKIP_SECTION_PATTERNS:
        if re.match(pat, line):
            return True
    return False


def scan_indices(lines, regex):
    """Return indices of lines matching regex, excluding skip sections."""
    indices = []
    for i, line in enumerate(lines):
        if re.match(regex, line) and not is_skip_section(line):
            indices.append(i)
    return indices


def split_at_indices(lines, indices):
    """Split a list of lines at the given indices into sub-blocks."""
    if not indices:
        return [lines] if lines else []

    blocks = []
    if indices[0] > 0:
        blocks.append(lines[: indices[0]])

    ends = indices[1:] + [len(lines)]
    for start, end in zip(indices, ends):
        block = lines[start:end]
        if block:
            blocks.append(block)
    return blocks


def infer_param_type(param_name, params_str, desc_lines, base_name):
    """
    Infer the Lua type for a parameter.

    Priority:
    1. Known params for specific function
    2. Heuristic from parameter name
    3. 'any' as fallback
    """
    # Check known overrides for this function
    if base_name in KNOWN_PARAMS and param_name in KNOWN_PARAMS[base_name]:
        return KNOWN_PARAMS[base_name][param_name]

    # Check parameter name heuristics
    if param_name in PARAM_TYPE_HINTS:
        return PARAM_TYPE_HINTS[param_name]

    # Look for type hints in description lines
    for line in desc_lines:
        if re.search(rf"(?i)`{re.escape(param_name)}`\s+is\s+a\s+string", line):
            return "string"
        if re.search(rf"(?i)`{re.escape(param_name)}`\s+is\s+a\s+Boolean", line):
            return "boolean"
        if re.search(rf"(?i)`{re.escape(param_name)}`\s+is\s+(a\s+)?number", line):
            return "number"
        if re.search(rf"(?i)`{re.escape(param_name)}`\s+is\s+a\s+table", line):
            return "table"

    return "any"


def infer_return_type(desc_lines, base_name):
    """
    Infer return type annotations from description text.

    Returns list of @return annotation strings, or empty list.
    """
    # Check known returns first
    if base_name in KNOWN_RETURNS:
        types = KNOWN_RETURNS[base_name]
        if len(types) == 1:
            return [f"---@return {types[0]}"]
        else:
            returns = []
            for t in types:
                returns.append(f"---@return {t}")
            return returns

    desc = " ".join(desc_lines)

    for pattern, rtype in RETURN_PATTERNS:
        if re.search(pattern, desc):
            if rtype is None:
                # Special handling for "returns a tuple of ..."
                m = re.search(pattern, desc)
                if m:
                    parts = m.group(1)
                    # Try to extract @return for each tuple element
                    items = re.findall(r"[a-zA-Z0-9_]+", parts)
                    return [f"---@return {item}" for item in items]
                return []
            return [f"---@return {rtype}"]

    # Default: check for "On error, nil, error" pattern
    if re.search(r"(?i)on\s+error,?\s+`?nil`?,\s*`?error`?", desc):
        return ["---@return any|nil", '---@return nil|string']

    return []


def extract_params_and_overloads(func_line):
    """
    Extract parameter info and generate overload function signatures.

    Returns (base_name, params_info, overloads)
    - base_name: e.g. "mp.get_property"
    - params_info: list of dicts with keys: name, is_optional, inferred_type
    - overloads: list of "function xxx(...) end\\n" strings
    """
    m = re.match(r"`([a-zA-Z0-9_.]+)\((.*)\)`", func_line)
    if not m:
        return None, [], []

    base_name = m.group(1)
    params_str = m.group(2).strip()

    # Special case: no params
    if not params_str:
        return base_name, [], [f"function {base_name}() end\n"]

    # ── Parse parameters ──
    # Handle vararg (...)
    if params_str == "...":
        return base_name, [{"name": "...", "is_optional": False, "type": "any"}], [
            f"function {base_name}(...) end\n"
        ]

    # Extract param names, preserving optional markers
    param_names = _extract_param_names(params_str)

    params_info = []
    for pname, is_optional in param_names:
        params_info.append(
            {
                "name": pname,
                "is_optional": is_optional,
                "type": "any",  # filled in later with description context
            }
        )

    # ── Generate overloads ──
    overloads = []
    has_brackets = "[" in params_str
    has_union = "|" in params_str or "/" in params_str

    if has_brackets or has_union:
        # Full version: all params
        all_params = _clean_params_str(params_str)
        overloads.append(f"function {base_name}({all_params}) end\n")

        # Base version: strip optional params
        base_raw = re.sub(r"\[.*?\]", "", params_str)
        base_raw = base_raw.replace("|", "|").replace("/", "|")
        base_params = ", ".join(
            re.findall(r"[a-zA-Z0-9_]+", base_raw)
        )
        if base_params and base_params != all_params:
            overloads.append(f"function {base_name}({base_params}) end\n")
    else:
        overloads.append(f"function {base_name}({params_str}) end\n")

    return base_name, params_info, overloads


def _extract_param_names(params_str):
    """
    Extract parameter names from a params string like "str [, trail]" or "name, fn".

    Returns list of (name, is_optional) tuples.
    Handles:
      - Simple: "name, fn" → [("name", False), ("fn", False)]
      - Optional: "str [, trail]" → [("str", False), ("trail", True)]
      - Vararg: "..." → "..."
    """
    # Normalize: remove outer whitespace, collapse spaces
    s = params_str.strip()

    # Split on commas, respecting brackets
    parts = _split_params(s)

    result = []
    for part in parts:
        part = part.strip()
        if not part:
            continue

        # Check if entire part is optional (wrapped in [...])
        m = re.match(r"\[(.+)\]", part)
        if m:
            inner = m.group(1).strip()
            # Inside the brackets, extract the param name
            names = re.findall(r"[a-zA-Z0-9_]+", inner)
            if names:
                name = names[0]  # take the first name
                # Check if there's a default or type annotation like `trail`
                result.append((name, True))
            continue

        # Check for patterns like "name, [opt]" or "name, fn"
        # Just split on commas and process each
        sub_names = re.findall(r"[a-zA-Z0-9_]+", part)
        if sub_names:
            result.append((sub_names[0], False))

    return result


def _split_params(params_str):
    """Split params string on commas, respecting nested brackets."""
    parts = []
    depth = 0
    current = ""
    for ch in params_str:
        if ch == "[":
            depth += 1
            current += ch
        elif ch == "]":
            depth -= 1
            current += ch
        elif ch == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += ch
    if current:
        parts.append(current)
    return parts


def _clean_params_str(params_str):
    """Clean a params string for use as a function signature: normalize separators."""
    s = params_str.replace("|", "_").replace("/", "_")
    names = re.findall(r"[a-zA-Z0-9_]+", s)
    return ", ".join(names)


def clean_description_line(line):
    """Clean up a markdown description line for use as a Lua comment."""
    line = line.rstrip("\n")
    line = line.rstrip()
    return line


def _process_one_func(sb, code_regex):
    """
    Process a single sub-block containing a function signature and its docs.

    Returns a list of output lines, or None if the sub-block should be skipped.
    """
    first_line = sb[0]
    m = re.match(code_regex, first_line)
    if not m:
        return None

    func_line = first_line.strip()

    # Extract params and generate overloads
    base_name, params_info, overloads = extract_params_and_overloads(func_line)

    if base_name is None:
        return None

    # Skip duplicates (same function name + signature)
    sig_match = re.match(r"`[a-zA-Z0-9_.]+\((.*)\)`", func_line)
    params_raw = sig_match.group(1) if sig_match else ""
    if is_duplicate(base_name, params_raw):
        return None

    # Collect description lines
    desc_lines = [clean_description_line(line) for line in sb[1:]]

    # --- Generate @param annotations ---
    param_anns = []
    for info in params_info:
        pname = info["name"]
        inferred_type = infer_param_type(
            pname, params_raw, desc_lines + [func_line], base_name
        )
        opt_mark = "?" if info["is_optional"] else ""
        param_anns.append(f"---@param {pname}{opt_mark} {inferred_type}\n")

    # --- Generate @return annotations ---
    return_anns = infer_return_type(desc_lines, base_name)

    # --- Assemble ---
    # Format: description + @param + @return + overloads + blank line
    output = []
    for line in desc_lines:
        if line:
            output.append(f"-- {line}\n")
        else:
            output.append("--\n")
    output.extend(param_anns)
    output.extend(r + '\n' for r in return_anns)
    output.extend(overloads)
    output.append("\n")

    return output


