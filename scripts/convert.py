# ── Main pipeline ──────────────────────────────────────────────────────────────


def run_pipeline():
    print("🔧 Generating mpv Lua stubs...")
    ensure_dir(os.path.join(LIBRARY_DIR, "mp"))

    md_lines = read_lines(LUA_MD)

    # Step 1: Split by headings
    heading_indices = scan_indices(md_lines, r"^##.*")
    heading_blocks = split_at_indices(md_lines, heading_indices)

    # Step 2: Assign blocks to modules
    for block in heading_blocks:
        assigned = False
        for mod in modules[1:]:
            if mod.keyword and re.match(mod.keyword, block[0]):
                mod.content_arr.append(block)
                assigned = True
                break
        if not assigned:
            modules[0].content_arr.append(block)

    # Step 3: Process each module — split blocks into functions
    code_regex = r"^`[a-zA-Z0-9_.]+\(.*?\)`"

    for mod in modules:
        reset_seen_funcs()
        new_mod_blocks = []

        for block in mod.content_arr:
            # Find function signature lines in this block
            func_indices = scan_indices(block, code_regex)
            sub_blocks = split_at_indices(block, func_indices)

            processed_subs = []
            for sb in sub_blocks:
                if not sb:
                    continue

                first_line = sb[0]
                m = re.match(code_regex, first_line)

                if not m:
                    # Non-function content (e.g. intro paragraph) — skip
                    continue

                # Handle comma-separated function signatures on one line
                # e.g. `msg.fatal(...)`, `msg.error(...)`, ...
                all_func_sigs = re.findall(
                    r"`[a-zA-Z0-9_.]+\(\.\.\.\)`", first_line
                )
                if len(all_func_sigs) > 1:
                    # Split into multiple separate entries
                    for sig in all_func_sigs:
                        sb_copy = [sig + "\n"] + sb[1:]
                        result = _process_one_func(sb_copy, code_regex)
                        if result:
                            processed_subs.append(result)
                    continue

                result = _process_one_func(sb, code_regex)
                if result:
                    processed_subs.append(result)

            new_mod_blocks.append(processed_subs)

        mod.content_arr = new_mod_blocks

    # Step 4: Write output files
    for mod in modules:
        output_lines = ["---@meta\n"]

        if mod.name == "mp":
            output_lines.append("mp = mp\n\n")
            # Add class definitions
            output_lines.extend(get_class_definitions())
        else:
            output_lines.append(f"{mod.name} = {{}}\n\n")

        for block in mod.content_arr:
            for sub_block in block:
                output_lines.extend(sub_block)
            output_lines.append("\n")

        output_lines.append(f"return {mod.name}\n")

        try:
            with open(mod.path, "w", encoding="utf-8") as f:
                f.writelines(output_lines)
            print(f"  ✅ {mod.name} → {mod.path}")
        except IOError as e:
            print(f"  ❌ Failed to write {mod.path}: {e}", file=sys.stderr)
            sys.exit(1)

    print("🎉 Done!")


if __name__ == "__main__":
    run_pipeline()
